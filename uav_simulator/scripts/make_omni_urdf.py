#!/usr/bin/env python3
"""Write urdf/quadcopter_omni.urdf from urdf/quadcopter_lidar.urdf: the same drone, with the tilted Mid-360 swapped for
the ideal 360 depth sensor where an Insta360 would sit (level, 0.24 m above base_link, full sphere less the cone the
drone blocks, scan pattern omni360-ideal.csv). Its raw points go to /omni/cloud_raw in omni_link; flow_limited_cloud.py
keeps the ones optic flow could measure. Run it again after changing quadcopter_lidar.urdf.
"""
import os

here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'urdf')
src = open(os.path.join(here, 'quadcopter_lidar.urdf')).read()
swaps = [
    ('<sensor type="ray" name="laser_livox">', '<sensor type="ray" name="omni360_ideal">'),
    ('<pose>0 0 0.13 0 ${radians($(arg lidar_pitch_deg))} 0</pose> <!-- Mid-360 pitched nose-down (xacro arg lidar_pitch_deg, 23.5 on the real drone) -->',
     '<pose>0 0 0.24 0 0 0</pose> <!-- ideal 360 depth at the Insta360 position: level, on a mast above the lidar -->'),
    ('<csv_file_name>mid360-real-centr.csv</csv_file_name>', '<csv_file_name>omni360-ideal.csv</csv_file_name>'),
    ('<ros_topic>/cloud_registered_body</ros_topic>', '<ros_topic>/omni/cloud_raw</ros_topic>'),
    ('<frameName>lidar_link</frameName> <!-- points are in the tilted sensor frame; base_link -> lidar_link is published in setupTF.launch -->',
     '<frameName>omni_link</frameName> <!-- level, 0.24 m above base_link; published in setupTF.launch -->'),
    ('<max>40</max>', '<max>25</max>'),
    # start rays beyond the drone (1.5x CERLAB mesh, rotors ~0.4 m out): the camera's own drone is masked out of the
    # flow, so it must not appear as an obstacle around itself
    ('<min>0.1</min>', '<min>0.6</min>'),
]
out = src
for a, b in swaps:
    assert out.count(a) == 1, 'not found once in quadcopter_lidar.urdf: ' + a
    out = out.replace(a, b)
out = out.replace('<robot name="quadcopter" xmlns:xacro="http://www.ros.org/wiki/xacro">', '<robot name="quadcopter" xmlns:xacro="http://www.ros.org/wiki/xacro">\n  <!-- generated by scripts/make_omni_urdf.py from quadcopter_lidar.urdf: edit that and rerun -->', 1)
open(os.path.join(here, 'quadcopter_omni.urdf'), 'w').write(out)
print('Wrote', os.path.normpath(os.path.join(here, 'quadcopter_omni.urdf')))

# quadcopter_omni_cam.urdf: the same, plus the two real fisheye images (Insta360-style, 200 deg equidistant, 640 px,
# 15 Hz) at the same spot, for optic flow on images and for demo videos. Rendering them slows the sim, so it is separate.
LENS = """  <gazebo reference="base_link">
    <sensor name="insta360_{name}" type="wideanglecamera">
      <pose>0 0 0.24 0 0 {yaw}</pose>
      <always_on>true</always_on>
      <update_rate>15</update_rate>
      <camera>
        <horizontal_fov>3.4907</horizontal_fov>
        <image><width>640</width><height>640</height><format>R8G8B8</format></image>
        <clip><near>0.05</near><far>100</far></clip>
        <lens><type>equidistant</type><scale_to_hfov>true</scale_to_hfov><cutoff_angle>1.7453</cutoff_angle><env_texture_size>512</env_texture_size></lens>
      </camera>
      <plugin name="insta360_{name}_ros" filename="libgazebo_ros_camera.so">
        <cameraName>insta360/{name}</cameraName>
        <imageTopicName>image_raw</imageTopicName>
        <cameraInfoTopicName>camera_info</cameraInfoTopicName>
        <frameName>insta360_{name}</frameName>
        <updateRate>0</updateRate>
      </plugin>
    </sensor>
  </gazebo>
"""
cams = ''.join(LENS.format(name=n, yaw=y) for n, y in (('front', 0), ('back', 3.14159265)))
cam = out.replace('</robot>', cams + '</robot>')
open(os.path.join(here, 'quadcopter_omni_cam.urdf'), 'w').write(cam)
print('Wrote', os.path.normpath(os.path.join(here, 'quadcopter_omni_cam.urdf')))

# quadcopter_omni_lidar(_cam).urdf: both sensors, the tilted Mid-360 (/cloud_registered_body) and the ideal 360 depth
# sensor (/omni/cloud_raw), for fusing them (the lidar ranges straight ahead, where optic flow cannot)
start = out.index('  <gazebo reference="base_link">\n    <sensor type="ray" name="omni360_ideal">')
end = out.index('</gazebo>', start) + len('</gazebo>')
omni_block = out[start:end] + '\n'
both = src.replace('</robot>', omni_block + '</robot>').replace('<robot name="quadcopter">', '<robot name="quadcopter">\n  <!-- generated by scripts/make_omni_urdf.py: quadcopter_lidar.urdf + the ideal 360 depth sensor -->', 1)
open(os.path.join(here, 'quadcopter_omni_lidar.urdf'), 'w').write(both)
open(os.path.join(here, 'quadcopter_omni_lidar_cam.urdf'), 'w').write(both.replace('</robot>', cams + '</robot>'))
print('Wrote quadcopter_omni_lidar.urdf and quadcopter_omni_lidar_cam.urdf')
